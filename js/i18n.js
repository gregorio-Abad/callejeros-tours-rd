const STORAGE_KEY = 'callejerosLanguage';
const DEFAULT_LANG = 'es';

function getStoredLanguage() {
  const lang = localStorage.getItem(STORAGE_KEY);
  if (lang === 'en' || lang === 'es') {
    return lang;
  }
  return DEFAULT_LANG;
}

function setLanguage(lang) {
  // Validate language
  if (lang !== 'es' && lang !== 'en') {
    lang = DEFAULT_LANG;
  }

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Save to localStorage
  localStorage.setItem(STORAGE_KEY, lang);

  // Dispatch global event for app logic (e.g. dynamic cards/modals)
  document.dispatchEvent(new CustomEvent("languageChanged", {
    detail: { lang }
  }));

  // Apply translations to all elements with data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      const translatedText = translations[lang][key];
      
      // Update text content
      if (el.hasAttribute('placeholder') && el.tagName === 'INPUT') {
          el.setAttribute('placeholder', translatedText);
      } else {
          el.innerHTML = translatedText;
      }
    }
  });
  
  // Future proofing for aria-label, title etc.
  const ariaLabelElements = document.querySelectorAll('[data-i18n-aria]');
  ariaLabelElements.forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('aria-label', translations[lang][key]);
    }
  });

  const titleElements = document.querySelectorAll('[data-i18n-title]');
  titleElements.forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('title', translations[lang][key]);
    }
  });
}

function toggleLanguage() {
  const currentLang = document.documentElement.lang;
  const newLang = currentLang === 'es' ? 'en' : 'es';
  setLanguage(newLang);
}

document.addEventListener('DOMContentLoaded', () => {
  // 1. Load initial language
  const initialLang = getStoredLanguage();
  setLanguage(initialLang);

  // 2. Attach event listener to the switcher
  const switcherBtn = document.getElementById('languageSwitcher');
  if (switcherBtn) {
    switcherBtn.addEventListener('click', toggleLanguage);
  }
});
